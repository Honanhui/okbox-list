import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync(new URL('../server.js',import.meta.url),'utf8');
let clientId='phone';
const config={activeId:'default',revision:7,configUrls:[{id:'a',enabled:true},{id:'b',enabled:true}],deviceSelections:{}};
const sites=[{configId:'a',key:'a:site'},{configId:'b',key:'b:site'}];
const context=vm.createContext({config,tvboxSites:sites,requestContext:{getStore:()=>({clientId})},isCatSetupSite:()=>false,createError:(_code,message)=>new Error(message),saveConfig:async next=>Object.assign(config,next),subscriptionCatalog:()=>({activeId:context.selectedSubscriptionId()} )});
vm.runInContext(source.slice(source.indexOf('function selectedSubscriptionId()'),source.indexOf('function subscriptionCatalog()')),context);
vm.runInContext(source.slice(source.indexOf('async function subscriptionAction(body)'),source.indexOf('function publicConfig()')),context);
await context.subscriptionAction({action:'select',id:'a'});
clientId='emulator';await context.subscriptionAction({action:'select',id:'b'});
assert.equal(context.selectedSubscriptionId(),'b');
clientId='phone';assert.equal(context.selectedSubscriptionId(),'a');
assert.equal(context.activeTvboxSites()[0].key,'a:site');
clientId='browser';await context.subscriptionAction({action:'select',id:'b'});
clientId='phone';assert.equal(context.selectedSubscriptionId(),'a');
assert.equal(config.activeId,'default');assert.equal(config.revision,7);
assert.equal(sites.find(site=>site.key==='a:site').configId,'a');
console.log('PASS: phone, emulator and browser selections are independent; global revision and playback site keys stay unchanged');
